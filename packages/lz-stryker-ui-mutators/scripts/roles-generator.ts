import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

import { findManifest, readRoleTable } from '../src/playwright-roles.ts';

function reason(error: unknown): string {
  return error instanceof Error ? error.message : String(error);
}

function manifestFrom(from: string): string {
  let manifest: string | undefined;

  try {
    manifest = findManifest(createRequire(from).resolve);
  } catch (error) {
    throw new Error(
      `cannot resolve playwright-core from ${from}: ${reason(error)}.`,
    );
  }

  if (manifest === undefined) {
    throw new Error(
      `playwright-core is not installed where ${from} resolves it; it is a dev dependency of this package.`,
    );
  }

  return manifest;
}

export function generateRoles(from: string, out: string): void {
  const { version, roles } = readRoleTable(manifestFrom(from));
  const entries = [...roles]
    .map(([tag, { role, requiredAttribute }]) =>
      requiredAttribute === undefined
        ? `    ['${tag}', { role: '${role}' }],`
        : `    ['${tag}', { role: '${role}', requiredAttribute: '${requiredAttribute}' }],`,
    )
    .sort()
    .join('\n');

  writeFileSync(
    out,
    `// Generated by scripts/generate-roles.ts from playwright-core ${version}. Do not edit.
import type { BundledRoles } from './playwright-roles.ts';

/** The role table of playwright-core ${version}, for consumers without playwright-core or with one it cannot read. */
export const bundled: BundledRoles = {
  version: '${version}',
  roles: new Map([
${entries}
  ]),
};
`,
  );
}
