import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join } from 'node:path';

import {
  findManifest,
  parseRoleTable,
  readPlaywrightCore,
  type PlaywrightCore,
} from '../src/playwright-roles.ts';

const from =
  process.env['LZ_UI_MUTATORS_ROLES_FROM'] ??
  join(import.meta.dirname, '..', 'package.json');
const out =
  process.env['LZ_UI_MUTATORS_ROLES_OUT'] ??
  join(import.meta.dirname, '..', 'src', 'bundled-roles.ts');

function fail(message: string): never {
  process.stderr.write(`lz-stryker-ui-mutators build: ${message}\n`);
  process.exit(1);
}

function reason(error: unknown): string {
  return error instanceof Error ? error.message : String(error);
}

let core: PlaywrightCore | undefined;

try {
  const manifest = findManifest(createRequire(from).resolve);
  core = manifest === undefined ? undefined : readPlaywrightCore(manifest);
} catch (error) {
  fail(`cannot resolve playwright-core from ${from}: ${reason(error)}.`);
}

if (core === undefined) {
  fail(
    `playwright-core is not installed where ${from} resolves it; it is a dev dependency of this package.`,
  );
}

let entries: string;

try {
  entries = [...parseRoleTable(readFileSync(core.bundlePath, 'utf8'))]
    .map(([tag, { role, requiredAttribute }]) =>
      requiredAttribute === undefined
        ? `    ['${String(tag)}', { role: '${role}' }],`
        : `    ['${String(tag)}', { role: '${role}', requiredAttribute: '${requiredAttribute}' }],`,
    )
    .sort()
    .join('\n');
} catch (error) {
  fail(
    `cannot read the implicit role table of playwright-core ${core.version} in ${core.bundlePath}: ${reason(error)}.`,
  );
}

writeFileSync(
  out,
  `// Generated by scripts/generate-roles.ts from playwright-core ${core.version}. Do not edit.
import type { BundledRoles } from './playwright-roles.ts';

/** The role table of playwright-core ${core.version}, for consumers without playwright-core or with one it cannot read. */
export const bundled: BundledRoles = {
  version: '${core.version}',
  roles: new Map([
${entries}
  ]),
};
`,
);
