export function add(a: number, b: number): number {
  return a + b;
}

export function countTo(n: number): number {
  let i = 0;

  while (i < n) {
    i++;
  }

  return i;
}

export function double(n: number): number {
  return n * 2;
}

export function half(n: number): number {
  return n / 2;
}
